import os
import win32com.client as win32

def ejecutar_macro_excel(ruta_libro, nombre_macro):

    if not os.path.exists(ruta_libro):
        print(f"Error: No se encontró el archivo en la ruta: {ruta_libro}")
        return False

    ruta_absoluta = os.path.abspath(ruta_libro)

    excel = None

    try:
        excel = win32.Dispatch("Excel.Application")
        excel.Visible = False
        excel.DisplayAlerts = False

        print(f"Abriendo el archivo: {ruta_absoluta}...")
        workbook = excel.Workbooks.Open(ruta_absoluta)

        print(f"Ejecutando la macro: '{nombre_macro}'...")
        nombre_archivo = os.path.basename(ruta_absoluta)

        excel.Application.Run(f"'{nombre_archivo}'!{nombre_macro}")

        workbook.Save()
        workbook.Close(SaveChanges=True)

        print("[✓] Macro ejecutada y archivo guardado exitosamente.")
        return True

    except Exception as e:
        print(f"[✗] Ocurrió un error al ejecutar la macro: {e}")
        return False

    finally:
        if excel:
            excel.Quit()
            del excel
            print("Proceso de Excel finalizado correctamente.")

